import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";

// These names are the audited mapping from the former AXORA icon components.
export const aliases = {
  ArrowRight: "arrow-right", ArrowLeft: "arrow-left", ChevronLeft: "chevron-left",
  ChevronDown: "chevron-down", Close: "x", Menu: "menu", MenuShort: "menu",
  Plus: "plus", Check: "check", Search: "search", SearchEmpty: "search",
  Info: "info-circle", Alert: "circle-alert", Upload: "upload", Download: "download",
  Refresh: "refresh", Desktop: "monitor", Tablet: "tablet", Phone: "smartphone",
  Home: "home", Grid: "layout-grid", Sliders: "adjustments", Form: "file-text",
  PhoneCall: "phone", Mail: "mail", Chat: "message", Clock: "clock", Pages: "copy",
  Gear: "settings", Image: "photo", Globe: "globe", File: "file-text", Sun: "sun",
  Moon: "moon", Dashboard: "layout-grid", Inbox: "inbox", Box: "cube", More: "dots",
  Pencil: "pencil", Filter: "filter", Copy: "copy", Lock: "lock", Monitor: "monitor",
};
const names = [...new Set([...Object.values(aliases), "heart", "credit-card", "swap", "letter-a", "external-link", "minus", "table", "circle-record", "diamond", "arrow-up", "arrow-down", "bell", "activity", "circle-check", "circle-x", "eye", "eye-off", "chevron-right"])].sort();
const symbols = [];
for (const name of names) {
  const svg = readFileSync(`vendor/regen-icons/svg/outline/${name}.svg`, "utf8").trim();
  if (!svg.includes('viewBox="0 0 24 24"') || /<script|<image|\bon\w+=/.test(svg)) throw new Error(`Invalid SVG: ${name}`);
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")}</symbol>`);
}
const heart = readFileSync("vendor/regen-icons/svg/filled/heart.svg", "utf8").trim();
symbols.push(`<symbol id="heart-filled" viewBox="0 0 24 24">${heart.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")}</symbol>`);
mkdirSync("public/icons", { recursive: true });
writeFileSync("public/icons/regen.svg", `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`);
copyFileSync("vendor/regen-icons/LICENSE", "public/icons/REGEN-LICENSE.txt");
writeFileSync("src/components/ui/icon-names.ts", `// Generated by scripts/generate-regen-icons.mjs. Do not edit.\nexport type IconName = ${[...names, "heart-filled"].map(n => JSON.stringify(n)).join(" | ")};\n`);
// Preserve the existing favicon background and colors; the mark is Regen letter-a.
const letter = readFileSync("vendor/regen-icons/svg/outline/letter-a.svg", "utf8").trim().replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
writeFileSync("src/app/icon.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="18" fill="#173c2d"/><g transform="translate(12 12) scale(1.6666667)" fill="none" stroke="#d9f279" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${letter}</g></svg>\n`);
console.log(`Generated ${symbols.length} Regen symbols from verified SVG files.`);
